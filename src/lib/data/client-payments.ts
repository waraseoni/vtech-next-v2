import "server-only";

import { unwrap, unwrapMaybe } from "@/lib/data/errors";
import { createClient } from "@/lib/supabase/server";
import type { PaymentMode, PaymentType } from "@/lib/supabase/database.types";

export type ClientPaymentRow = {
  id: number;
  client_id: number;
  job_id: string | null;
  loan_id: number | null;
  bill_no: string | null;
  payment_date: string | null;
  amount: number;
  discount: number | null;
  net_amount: number | null;
  payment_mode: PaymentMode | null;
  payment_type: PaymentType | null;
  remarks: string | null;
  created_at: string | null;
};

export type PaymentInput = {
  clientId: number;
  amount: number;
  discount?: number;
  paymentDate: string;
  paymentMode: PaymentMode;
  paymentType: PaymentType;
  jobId?: string | null;
  billNo?: string | null;
  loanId?: number | null;
  remarks?: string | null;
};

const PAYMENT_COLUMNS =
  "id, client_id, job_id, loan_id, bill_no, payment_date, amount, discount, net_amount, payment_mode, payment_type, remarks, created_at";

export type PaymentRange = { from?: string; to?: string; limit?: number };

export async function listClientPayments(
  clientId: number,
  { from = "", to = "", limit = 200 }: PaymentRange = {},
): Promise<ClientPaymentRow[]> {
  const supabase = await createClient();
  let query = supabase
    .from("client_payments")
    .select(PAYMENT_COLUMNS)
    .eq("client_id", clientId)
    .order("payment_date", { ascending: false })
    .order("id", { ascending: false })
    .limit(Math.min(1000, Math.max(1, limit)));

  if (from) query = query.gte("payment_date", from);
  if (to) query = query.lte("payment_date", to);

  return unwrap(await query, "clients.payments") as ClientPaymentRow[];
}

/** Every payment for the ledger (payments link to loans via `loan_id`). */
export async function listClientPaymentsForLedger(
  clientId: number,
): Promise<ClientPaymentRow[]> {
  return listClientPayments(clientId, { limit: 1000 });
}

export async function getClientPayment(
  clientId: number,
  paymentId: number,
): Promise<ClientPaymentRow | null> {
  const supabase = await createClient();
  const result = await supabase
    .from("client_payments")
    .select(PAYMENT_COLUMNS)
    .eq("client_id", clientId)
    .eq("id", paymentId)
    .maybeSingle();
  return unwrapMaybe(result, "clients.payment") as ClientPaymentRow | null;
}

function toInsert(input: PaymentInput) {
  return {
    client_id: input.clientId,
    amount: input.amount,
    discount: input.discount ?? 0,
    payment_date: input.paymentDate,
    payment_mode: input.paymentMode,
    payment_type: input.paymentType,
    job_id: input.jobId || null,
    bill_no: input.billNo || null,
    loan_id: input.loanId ?? null,
    remarks: input.remarks || null,
  };
}

function toUpdate(input: PaymentInput) {
  return {
    amount: input.amount,
    discount: input.discount ?? 0,
    payment_date: input.paymentDate,
    payment_mode: input.paymentMode,
    payment_type: input.paymentType,
    job_id: input.jobId || null,
    bill_no: input.billNo || null,
    loan_id: input.loanId ?? null,
    remarks: input.remarks || null,
  };
}

/** `net_amount` is generated by the DB — never send it. */
export async function createClientPayment(input: PaymentInput) {
  const supabase = await createClient();
  const result = await supabase
    .from("client_payments")
    .insert(toInsert(input))
    .select("id")
    .single();
  return unwrap(result, "clients.payment.create") as { id: number };
}

export async function updateClientPayment(
  paymentId: number,
  input: PaymentInput,
) {
  const supabase = await createClient();
  const result = await supabase
    .from("client_payments")
    .update(toUpdate(input))
    .eq("id", paymentId)
    .select("id")
    .single();
  return unwrap(result, "clients.payment.update") as { id: number };
}

export async function deleteClientPayment(paymentId: number) {
  const supabase = await createClient();
  const result = await supabase
    .from("client_payments")
    .delete()
    .eq("id", paymentId)
    .select("id")
    .single();
  return unwrap(result, "clients.payment.delete");
}

export type PaymentReportFilters = {
  from?: string;
  to?: string;
  mode?: PaymentMode | "";
  clientId?: number;
  page?: number;
  pageSize?: number;
};

export type PaymentReport = {
  rows: ClientPaymentRow[];
  total: number;
  page: number;
  pageSize: number;
};

export async function getPaymentReport({
  from = "",
  to = "",
  mode,
  clientId,
  page = 1,
  pageSize = 50,
}: PaymentReportFilters): Promise<PaymentReport> {
  const supabase = await createClient();
  const safePage = Math.max(1, page);
  const safeSize = Math.min(100, Math.max(10, pageSize));
  const start = (safePage - 1) * safeSize;

  let query = supabase
    .from("client_payments")
    .select(PAYMENT_COLUMNS, { count: "exact" })
    .order("payment_date", { ascending: false })
    .order("id", { ascending: false })
    .range(start, start + safeSize - 1);

  if (from) query = query.gte("payment_date", from);
  if (to) query = query.lte("payment_date", to);
  if (mode) query = query.eq("payment_mode", mode);
  if (clientId) query = query.eq("client_id", clientId);

  const result = await query;
  const rows = unwrap(result, "clients.payment.report") as ClientPaymentRow[];
  return {
    rows,
    total: result.count ?? rows.length,
    page: safePage,
    pageSize: safeSize,
  };
}
